// Run with node tests/test_biren_finance_model.cjs. No browser dependencies.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const context = {};
context.window=context;
vm.createContext(context);
const root = path.join(__dirname,'../demos/biren-finance');
for (const file of ['data.js','model.js']) vm.runInContext(fs.readFileSync(path.join(root,'js',file),'utf8'),context);
const M=context.window.BIREN_MODEL;
const close=(a,b)=>assert(Math.abs(a-b)<0.001,`${a} != ${b}`);
close(M.sum(M.budget,'annual'),49800);
close(M.sum(M.budget,r=>r.monthlyActual.reduce((a,b)=>a+b,0)),31040);
close(M.sum(M.rd,'budget'),20400);
close(M.sum(M.rd,'used'),16740);
close(M.sum(M.inventory,'amount'),38620);
close(M.sum(M.inventory,'qty'),102.2);
close(M.people.reduce((n,p)=>n+M.personal(p,[1,2,3,4,5,6,7]).order,0),M.sum(M.sales,'order'));
for (const r of M.sales) close(r.allocations.reduce((n,a)=>n+a.share,0),1);
const quarter=M.salesFilter({months:[4,5,6],customer:'客户A'});
assert.equal(quarter.length,3);
assert(quarter.every(r=>r.customer==='客户A'&&[4,5,6].includes(r.month)));
const own=M.personal('张明',[7]);
assert(own.rows.every(r=>r.allocations.some(a=>a.person==='张明')));
assert.equal(own.orderTarget,1200);
assert.equal(M.salesFilter({person:'张明',customer:'客户F'}).length,0);
assert(M.inventoryFilter({category:'原材料',project:'BR100'}).every(r=>r.category==='原材料'&&r.project==='BR100'));
const all=M.arFilter({});
close(M.sum(all,'amount'),M.sum(all.filter(r=>M.age(r.due)>=0),'amount')+M.sum(all.filter(r=>M.age(r.due)<0),'amount'));
assert(M.arFilter({team:'华东团队'}).every(r=>r.team==='华东团队'));
assert.equal(M.forms.length,10);
assert.deepEqual([...new Set(M.budget.map(r=>r.attribute))].sort(),['研发','管理','销售','量产'].sort());
assert.deepEqual([...new Set(M.budget.map(r=>r.expenseType))].sort(),['工程NRE','部门行政费用'].sort());
console.log('Biren finance: aggregation, allocation, targets, scope filters and receivable reconciliation passed.');
